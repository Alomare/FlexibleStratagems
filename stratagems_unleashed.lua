-- Frame step

local state = {ready = false, screen = nil}

local function leave_screen()
    restore_vehicles()
    state.screen = nil
    visit.offers, visit.block, visit.refused = nil, nil, nil
end

local function loadout_screen()
    if not read_into(buffers.global, native.base + L.stack, 8) then return nil end
    local stack = buf_pointer(buffers.global, 0)
    if not stack or not read_into(buffers.stack, stack, L.slot + 8) then return nil end
    if buf_u32(buffers.stack, 0) ~= LOADOUT_SCREEN then return nil end
    return buf_pointer(buffers.stack, L.slot)
end

local function step()
    if not state.screen and M.frames % IDLE_POLL ~= 0 then return end
    local screen = loadout_screen()
    if screen ~= state.screen then
        if state.screen then leave_screen() end
        state.screen = screen
    end
    if not screen or not read_into(buffers.head, screen + SCREEN.head, SCREEN.head_size) then return end
    local index = buf_u32(buffers.head, SCREEN.local_index)
    if buf_u32(buffers.head, SCREEN.category) ~= STRATAGEMS or index > 3 then restore_vehicles(); return end
    service_list(screen, index)
end

local function unavailable(reason)
    write_status('NOT AVAILABLE - this game version is not supported (' .. reason .. '); the loadout works as normal')
    note('Not available: ' .. reason)
    M.retired = true
end

-- With the code located: the layout, the native functions, then ready.
local function finish_start()
    local good, reason = read_layout()
    if good then
        for name, sig in pairs({mark = 'marker', select = 'select'}) do
            local ctype = name == 'mark' and 'void (*)(uint64_t, uint32_t, uint8_t)'  -- (list, offer, selectable)
                          or 'uint8_t (*)(uint64_t, uint32_t)'                         -- (list, offer or 0)
            local cast_ok, fn = pcall(ffi.cast, ctype, native.base + code.found[sig])
            if not cast_ok then good, reason = false, 'native function ' .. name .. ' unavailable' end
            native[name] = fn
        end
    end
    if not good then return unavailable(reason) end
    make_buffers()
    local where = #code.moved == 0 and "at this game version's addresses"
                  or ('by search (' .. #code.moved .. ' moved: ' .. table.concat(code.moved, ', ') .. ')')
    write_status('OK - duplicate stratagems and vehicles can be picked in the Hellpod loadout', 'Game code found ' .. where)
    note('Game code found ' .. where)
    state.ready = true
end

local function start()
    local ok, why = init_native()
    if not ok then
        write_status('NOT AVAILABLE - ' .. why .. '; the loadout works as normal')
        M.retired = true
        return
    end
    local all, reason = locate_code()
    if all == nil then return unavailable(reason) end
    if all then return finish_start() end
    note('Searching game.dll for moved code: ' .. #code.scan.missing .. ' signature(s)')
end

local function frame()
    M.frames = M.frames + 1
    if M.frames == 1 then
        start()
    elseif code.scan then
        if scan_step() then
            local ok, reason = finish_scan()
            if ok then finish_start() else unavailable(reason) end
        end
    elseif state.ready then
        step()
    end
end

local original_update = rawget(_G, 'update')
update = function(dt, ...)
    if not M.retired then
        local ok, err = xpcall(frame, debug.traceback)
        if not ok then
            M.errors = M.errors + 1
            note('Error: ' .. tostring(err))
            pcall(restore_vehicles)
            if M.errors >= 5 then
                M.retired = true
                write_status('STOPPED - repeated errors; the loadout works as normal (see StratagemsUnleashed.log)')
            end
        end
    end
    if type(original_update) == 'function' then return original_update(dt, ...) end
end

note('Stratagems Unleashed ' .. M.version .. ' loaded')

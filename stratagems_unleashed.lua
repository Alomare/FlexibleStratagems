-- The layout, from the matched code

local L = {}      -- field name -> value (offsets) or rva (globals, functions)
local SCREEN, LIST, BLOCK = {}, {}, {}

-- Reads every field (a name used by several signatures must agree), then checks the pieces fit together.
local function read_layout()
    for _, sig in ipairs(SIGS) do
        local rva = code.found[sig.name]
        for name, spec in pairs(sig.fields) do
            local v = field_value(sig, rva, spec)
            if not v then return false, string.format('"%s" in code "%s" is inconsistent', name, sig.name) end
            if spec[1] == 'rip' and not in_section(v, false) then return false, 'global "' .. name .. '" not in data' end
            if spec[1] == 'call' and not in_section(v, true) then return false, 'function "' .. name .. '" not in code' end
            if L[name] and L[name] ~= v then return false, string.format('"%s" differs between signatures', name) end
            L[name] = v
        end
    end
    local found = code.found
    -- The functions: the refresh the handler calls holds refresh_a/b and calls the marker found on its own.
    if L.mark ~= found.marker then return false, 'the refresh does not call the marker' end
    for _, part in ipairs({'refresh_a', 'refresh_b'}) do
        if found[part] < L.refresh or found[part] > L.refresh + 0x1000 then return false, part .. ' outside the refresh' end
    end
    -- The spans read each frame: the screen head (local index .. category), the list (count .. selectable bytes),
    -- a loadout block (entries .. count).
    if L.category <= L.local_index or L.category - L.local_index > 0x1000 then return false, 'screen head layout' end
    SCREEN.head, SCREEN.head_size = L.local_index, L.category - L.local_index + 4
    SCREEN.local_index, SCREEN.category = 0, L.category - L.local_index
    SCREEN.blocks, SCREEN.block_size, SCREEN.list = L.block_base, L.block_stride, L.list
    LIST.span, LIST.count = L.list_count, 0
    LIST.selected, LIST.ids, LIST.selectable = L.selected - L.list_count, L.ids - L.list_count, L.selectable - L.list_count
    LIST.span_size = LIST.selectable + LIST_MAX
    for _, k in ipairs({'selected', 'ids', 'selectable'}) do
        if LIST[k] < 4 or LIST[k] > 0x1000 then return false, 'list layout (' .. k .. ')' end
    end
    if LIST.ids + LIST_MAX * 4 > LIST.selectable then return false, 'list layout (ids)' end
    BLOCK.entries, BLOCK.count = L.block_entries, L.block_count
    if BLOCK.count < BLOCK.entries + BLOCK_MAX * ENTRY_SIZE or BLOCK.count >= SCREEN.block_size then
        return false, 'loadout block layout'
    end
    if L.types < 2 or L.types > 0x1000 then return false, 'stratagem table size' end
    return true
end

---------------------------------------------------------------------------------------
-- Stratagem data

local function item_id(t)  -- the stratagem's item id (info +4), from the game's stratagem table
    local info = t and t > 0 and t < L.types and global(L.strat_table + t * 8)
    local head = info and read(info, 8)
    if head and u32(head, 0) == t then return u32(head, INFO_ID) end
end

-- Stratagem item id -> offer id, from the offers table's stratagem range (built once per screen visit).
local function offer_map()
    local map = {}
    local offers = global(L.offers)
    local first = offers and u32(read(offers + L.first, 4))
    local last = offers and u32(read(offers + L.last, 4))
    local count = offers and u32(read(offers + L.offers_count, 4))
    if not first or not last or not count or last <= first or last - first > 512 or count > 0x10000 then return map end
    local indices = read(offers + L.indices + first * 4, (last - first) * 4)
    for k = 0, last - first - 1 do
        local index = u32(indices, k * 4)
        local entry = index and index < count and read(offers + L.entries + index * OFFER_STRIDE, OFFER_STRIDE)
        if entry then map[u32(entry, OFFER_ITEM)] = u32(entry, OFFER_ID) end
    end
    return map
end

---------------------------------------------------------------------------------------
-- The vehicle rule: kind bits cleared while the list is open, restored after.

local vehicles = nil      -- {{info address, original flags, cleared flags}...}, found once
local vehicles_lifted = false

local function find_vehicles()
    local found = {}
    for t = 1, L.types - 1 do
        local info = global(L.strat_table + t * 8)
        local flags = info and u32(read(info, 4)) == t and u32(read(info + L.flags, 4))
        if flags and bit.band(flags, VEHICLE_BITS) ~= 0 then
            local cleared = bit.band(flags, bit.bnot(VEHICLE_BITS))
            if cleared < 0 then cleared = cleared + 4294967296 end
            found[#found + 1] = {info, flags, cleared}
        end
    end
    return found
end

local function lift_vehicles()
    if vehicles_lifted then return end
    vehicles_lifted = true
    vehicles = vehicles or find_vehicles()
    for _, v in ipairs(vehicles) do
        if u32(read(v[1] + L.flags, 4)) ~= v[2] then  -- the table moved or changed: look again
            vehicles = find_vehicles()
            break
        end
    end
    for _, v in ipairs(vehicles) do write(v[1] + L.flags, u32_bytes(v[3])) end
end

local function restore_vehicles()
    if not vehicles_lifted then return end
    vehicles_lifted = false
    for _, v in ipairs(vehicles or {}) do
        -- Only what still holds our value (never overwrite something the game changed meanwhile).
        if u32(read(v[1] + L.flags, 4)) == v[3] then write(v[1] + L.flags, u32_bytes(v[2])) end
    end
end


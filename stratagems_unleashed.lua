-- Finding the game's code. Each signature ('??' = any byte) is tried at this build's address; the ones not there
-- are searched for in game.dll's executable sections, SCAN_CHUNK bytes per frame, and must match exactly once.
-- Then each field is read from the matched code (every place it occurs must agree): a value, or the target of a
-- rip-relative operand or call.

local code = {sections = nil, found = {}, moved = {}, scan = nil}

local function parse_sig(sig)
    local bytes = {}
    for part in sig.text:gmatch('%S+') do bytes[#bytes + 1] = part ~= '??' and tonumber(part, 16) or false end
    local best_at, best_len, at, len = 1, 0, nil, 0  -- the longest run of fixed bytes is searched for
    for i = 1, #bytes + 1 do
        if bytes[i] then
            if not at then at, len = i, 0 end
            len = len + 1
            if len > best_len then best_at, best_len = at, len end
        else
            at = nil
        end
    end
    local anchor = {}
    for i = best_at, best_at + best_len - 1 do anchor[#anchor + 1] = string.char(bytes[i]) end
    sig.bytes, sig.anchor, sig.anchor_at = bytes, table.concat(anchor), best_at - 1
end

local function sig_matches(blob, pos, sig)  -- pos: 1-based start in blob
    local bytes = sig.bytes
    if pos < 1 or pos + #bytes - 1 > #blob then return false end
    for i = 1, #bytes do
        local b = bytes[i]
        if b and blob:byte(pos + i - 1) ~= b then return false end
    end
    return true
end

-- game.dll's sections: {rva, size, exec}.
local function pe_sections()
    local dos = read(native.base, 0x40)
    local pe = dos and dos:sub(1, 2) == 'MZ' and u32(dos, 0x3c)
    local nt = pe and pe < 0x10000 and read(native.base + pe, 0x18)
    if not nt or nt:sub(1, 4) ~= 'PE\0\0' then return nil end
    local count, opt = u16(nt, 6), u16(nt, 20)
    local headers = count and count <= 96 and read(native.base + pe + 24 + opt, count * 40)
    if not headers then return nil end
    local sections = {}
    for i = 0, count - 1 do
        local size, rva, flags = u32(headers, i * 40 + 8), u32(headers, i * 40 + 12), u32(headers, i * 40 + 36)
        if size > 0 then sections[#sections + 1] = {rva = rva, size = size, exec = flags >= 0x20000000
                                                     and math.floor(flags / 0x20000000) % 2 == 1} end
    end
    return sections
end

local function in_section(rva, exec)
    for _, s in ipairs(code.sections) do
        if s.exec == exec and rva >= s.rva and rva + 8 <= s.rva + s.size then return true end
    end
    return false
end

-- One step of the search: the next chunk of the executable sections. True when done.
local function scan_step()
    local scan = code.scan
    local s = scan.sections[scan.section]
    if not s then return true end
    local from = scan.offset
    local size = math.min(SCAN_CHUNK + 256, s.size - from)
    local pieces = {}
    local blob = read(native.base + s.rva + from, size)
    if blob then
        pieces[1] = {from, blob}
    else
        for off = from, from + size - 1, 0x10000 do  -- skip unreadable pages
            local piece = read(native.base + s.rva + off, math.min(0x10000 + 256, s.size - off))
            if piece then pieces[#pieces + 1] = {off, piece} end
        end
    end
    for _, piece in ipairs(pieces) do
        local piece_from, data = piece[1], piece[2]
        for _, sig in ipairs(scan.missing) do
            local init = 1
            while true do
                local at = data:find(sig.anchor, init, true)
                if not at then break end
                local start = at - sig.anchor_at
                local offset = piece_from + start - 1
                -- Matches starting in the overlap belong to the next chunk.
                if offset >= from and offset < from + SCAN_CHUNK and sig_matches(data, start, sig) then
                    local hits = scan.hits[sig.name]
                    hits[#hits + 1] = s.rva + offset
                end
                init = at + 1
            end
        end
    end
    scan.offset = from + SCAN_CHUNK
    if scan.offset >= s.size then scan.section, scan.offset = scan.section + 1, 0 end
    return scan.sections[scan.section] == nil
end

-- A field's value from the matched code; nil if its occurrences disagree.
local function field_value(sig, rva, spec)
    local blob = read(native.base + rva, #sig.bytes)
    local value
    for k, off in ipairs(spec[2]) do
        local v
        if spec[1] == 'u8' then v = blob and blob:byte(off + 1)
        elseif spec[1] == 'u32' then v = u32(blob, off)
        else v = blob and rva + spec[3][k] + i32(blob, off) end
        if not v or (value and v ~= value) then return nil end
        value = v
    end
    return value
end

-- Tries every signature at this build's address; starts a search for the others. True when all were there.
local function locate_code()
    code.sections = pe_sections()
    if not code.sections then return nil, 'game.dll headers unreadable' end
    local missing, exec = {}, {}
    for _, sig in ipairs(SIGS) do
        parse_sig(sig)
        local blob = read(native.base + sig.rva, #sig.bytes)
        if blob and sig_matches(blob, 1, sig) then code.found[sig.name] = sig.rva else missing[#missing + 1] = sig end
    end
    if #missing == 0 then return true end
    for _, s in ipairs(code.sections) do if s.exec then exec[#exec + 1] = s end end
    code.scan = {sections = exec, section = 1, offset = 0, missing = missing, hits = {}}
    for _, sig in ipairs(missing) do code.scan.hits[sig.name] = {} end
    return false
end

-- After the search: each missing signature needs exactly one match.
local function finish_scan()
    for _, sig in ipairs(code.scan.missing) do
        local hits = code.scan.hits[sig.name]
        if #hits ~= 1 then
            return false, string.format('code "%s" %s', sig.name, #hits == 0 and 'not found' or ('found ' .. #hits .. ' times'))
        end
        code.found[sig.name], code.moved[#code.moved + 1] = hits[1], sig.name
    end
    code.scan = nil
    return true
end


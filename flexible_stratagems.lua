-- The vehicle rule: kind bits cleared while the list is open, restored after.

local vehicles = nil      -- {{info address, original flags, cleared flags}...}, found once
local vehicles_lifted = false

local function find_vehicles()
    local found = {}
    for t = 1, L.types - 1 do
        local info = global(L.strat_table + t * 8)
        local flags = info and u32(read(info, 4)) == t and u32(read(info + L.flags, 4))
        if flags and bit.band(flags, VEHICLE_BITS) ~= 0 then
            local cleared = bit.band(flags, bit.bnot(VEHICLE_BITS))
            if cleared < 0 then cleared = cleared + 4294967296 end
            found[#found + 1] = {info, flags, cleared}
        end
    end
    return found
end

local function lift_vehicles()
    if vehicles_lifted then return end
    vehicles_lifted = true
    vehicles = vehicles or find_vehicles()
    for _, v in ipairs(vehicles) do
        if u32(read(v[1] + L.flags, 4)) ~= v[2] then  -- the table moved or changed: look again
            vehicles = find_vehicles()
            break
        end
    end
    for _, v in ipairs(vehicles) do write(v[1] + L.flags, u32_bytes(v[3])) end
end

local function restore_vehicles()
    if not vehicles_lifted then return end
    vehicles_lifted = false
    for _, v in ipairs(vehicles or {}) do
        -- Only what still holds our value (never overwrite something the game changed meanwhile).
        if u32(read(v[1] + L.flags, 4)) == v[3] then write(v[1] + L.flags, u32_bytes(v[2])) end
    end
end


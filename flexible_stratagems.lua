-- Stratagem data

local function info_of(t)  -- the stratagem's info (its type at +0), from the game's stratagem table
    local info = t and t > 0 and t < L.types and global(L.strat_table + t * 8)
    if info and u32(read(info, 4)) == t then return info end
end

local function item_id(t)  -- the stratagem's item id (info +4)
    local info = info_of(t)
    return info and u32(read(info + INFO_ID, 4))
end

-- Stratagem item id -> offer id, from the offers table's stratagem range (built once per screen visit).
local function offer_map()
    local map = {}
    local offers = global(L.offers)
    local first = offers and u32(read(offers + L.first, 4))
    local last = offers and u32(read(offers + L.last, 4))
    local count = offers and u32(read(offers + L.offers_count, 4))
    if not first or not last or not count or last <= first or last - first > 512 or count > 0x10000 then return map end
    local indices = read(offers + L.indices + first * 4, (last - first) * 4)
    for k = 0, last - first - 1 do
        local index = u32(indices, k * 4)
        local entry = index and index < count and read(offers + L.entries + index * OFFER_STRIDE, OFFER_STRIDE)
        if entry then map[u32(entry, OFFER_ITEM)] = u32(entry, OFFER_ID) end
    end
    return map
end

